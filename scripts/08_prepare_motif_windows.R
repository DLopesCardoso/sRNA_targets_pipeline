# ============================================================
# HELPER: CHECK REQUIRED COLUMNS
# ============================================================

check_columns <- function(
    df,
    required,
    label
) {
  
  missing_columns <- setdiff(
    required,
    names(df)
  )
  
  
  if (length(missing_columns) > 0) {
    
    stop(
      label,
      " is missing required column(s):\n",
      paste(
        missing_columns,
        collapse = ", "
      ),
      "\n\nAvailable columns:\n",
      paste(
        names(df),
        collapse = ", "
      )
    )
  }
}



# ============================================================
# HELPER: REVERSE COMPLEMENT
# ============================================================

reverse_complement <- function(sequence) {
  
  sequence <-
    toupper(sequence)
  
  
  bases <-
    strsplit(
      sequence,
      split = "",
      fixed = TRUE
    )[[1]]
  
  
  complement_table <- c(
    
    "A" = "T",
    "T" = "A",
    "G" = "C",
    "C" = "G",
    
    "N" = "N",
    
    # IUPAC ambiguity codes
    
    "R" = "Y",
    "Y" = "R",
    "S" = "S",
    "W" = "W",
    "K" = "M",
    "M" = "K",
    
    "B" = "V",
    "D" = "H",
    "H" = "D",
    "V" = "B"
  )
  
  
  unknown <-
    !bases %in%
    names(
      complement_table
    )
  
  
  bases[unknown] <-
    "N"
  
  
  complemented <-
    complement_table[
      bases
    ]
  
  
  paste0(
    rev(complemented),
    collapse = ""
  )
}



# ============================================================
# HELPER: READ FASTA
# ============================================================

read_fasta_base <- function(path) {
  
  lines <- readLines(
    path,
    warn = FALSE
  )
  
  
  header_rows <- which(
    startsWith(
      lines,
      ">"
    )
  )
  
  
  if (length(header_rows) == 0) {
    
    stop(
      "No FASTA headers were found in:\n",
      path
    )
  }
  
  
  records <- vector(
    "list",
    length(header_rows)
  )
  
  
  for (
    i in seq_along(
      header_rows
    )
  ) {
    
    start_row <-
      header_rows[i] + 1L
    
    
    if (
      i <
      length(header_rows)
    ) {
      
      end_row <-
        header_rows[i + 1L] - 1L
      
    } else {
      
      end_row <-
        length(lines)
    }
    
    
    sequence_lines <-
      if (
        start_row <= end_row
      ) {
        
        lines[
          start_row:end_row
        ]
        
      } else {
        
        character(0)
      }
    
    
    sequence <-
      paste0(
        sequence_lines,
        collapse = ""
      )
    
    
    sequence <-
      toupper(
        gsub(
          "[^A-Za-z]",
          "",
          sequence
        )
      )
    
    
    header <-
      sub(
        "^>",
        "",
        lines[
          header_rows[i]
        ]
      )
    
    
    record_name <-
      strsplit(
        header,
        "\\s+"
      )[[1]][1]
    
    
    records[[i]] <-
      tibble::tibble(
        
        sequence_name =
          record_name,
        
        sequence =
          sequence,
        
        sequence_length =
          nchar(sequence)
      )
  }
  
  
  dplyr::bind_rows(
    records
  )
}



# ============================================================
# HELPER: READ GENBANK ORIGIN SEQUENCE
# ============================================================
#
# This parser extracts nucleotide sequences from GenBank records.
#
# It is intentionally restricted to the sequence itself; gene
# annotation is taken from reference_gene_coordinates.csv.

read_genbank_sequence <- function(path) {
  
  lines <- readLines(
    path,
    warn = FALSE
  )
  
  
  locus_rows <- which(
    grepl(
      "^LOCUS\\s+",
      lines
    )
  )
  
  
  origin_rows <- which(
    grepl(
      "^ORIGIN",
      lines
    )
  )
  
  
  end_rows <- which(
    grepl(
      "^//",
      lines
    )
  )
  
  
  if (
    length(origin_rows) == 0
  ) {
    
    stop(
      "No ORIGIN section found in GenBank file:\n",
      path
    )
  }
  
  
  if (
    length(origin_rows) !=
    length(end_rows)
  ) {
    
    stop(
      "Could not pair GenBank ORIGIN and // sections."
    )
  }
  
  
  records <- vector(
    "list",
    length(origin_rows)
  )
  
  
  for (
    i in seq_along(
      origin_rows
    )
  ) {
    
    origin <-
      origin_rows[i]
    
    
    record_end <-
      end_rows[
        end_rows > origin
      ][1]
    
    
    sequence_lines <-
      lines[
        (origin + 1L):
          (record_end - 1L)
      ]
    
    
    sequence <-
      paste0(
        sequence_lines,
        collapse = ""
      )
    
    
    sequence <-
      toupper(
        gsub(
          "[^A-Za-z]",
          "",
          sequence
        )
      )
    
    
    previous_locus_rows <-
      locus_rows[
        locus_rows < origin
      ]
    
    
    if (
      length(
        previous_locus_rows
      ) > 0
    ) {
      
      locus_line <-
        lines[
          max(
            previous_locus_rows
          )
        ]
      
      
      fields <-
        strsplit(
          trimws(locus_line),
          "\\s+"
        )[[1]]
      
      
      sequence_name <-
        if (
          length(fields) >= 2
        ) {
          
          fields[2]
          
        } else {
          
          paste0(
            "record_",
            i
          )
        }
      
    } else {
      
      sequence_name <-
        paste0(
          "record_",
          i
        )
    }
    
    
    records[[i]] <-
      tibble::tibble(
        
        sequence_name =
          sequence_name,
        
        sequence =
          sequence,
        
        sequence_length =
          nchar(sequence)
      )
  }
  
  
  dplyr::bind_rows(
    records
  )
}



