# ============================================================
# FASTA WRITER
# ============================================================

write_fasta <- function(
    headers,
    sequences,
    path,
    width = 80L
) {
  
  connection <-
    file(
      path,
      open = "w"
    )
  
  
  on.exit(
    close(connection),
    add = TRUE
  )
  
  
  for (
    i in seq_along(
      sequences
    )
  ) {
    
    writeLines(
      paste0(
        ">",
        headers[i]
      ),
      connection
    )
    
    
    sequence <-
      sequences[i]
    
    
    starts <-
      seq(
        1L,
        nchar(sequence),
        by = width
      )
    
    
    sequence_lines <-
      substring(
        
        sequence,
        
        starts,
        
        pmin(
          starts +
            width -
            1L,
          
          nchar(sequence)
        )
      )
    
    
    writeLines(
      sequence_lines,
      connection
    )
  }
}



