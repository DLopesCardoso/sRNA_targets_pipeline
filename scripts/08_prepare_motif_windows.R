# ============================================================
# HELPER: CIRCULAR GENOME SUBSEQUENCE
# ============================================================
#
# Bacterial reference genomes are commonly circular.
#
# This permits windows close to coordinate 1 or the end of the
# chromosome to wrap across the origin rather than being
# truncated.

extract_circular_sequence <- function(
    sequence,
    start,
    end
) {
  
  genome_n <-
    nchar(sequence)
  
  
  positions <-
    seq.int(
      start,
      end
    )
  
  
  wrapped_positions <-
    (
      (
        positions -
          1L
      ) %%
        genome_n
    ) +
    1L
  
  
  bases <-
    substring(
      sequence,
      wrapped_positions,
      wrapped_positions
    )
  
  
  paste0(
    bases,
    collapse = ""
  )
}



# ============================================================
# CALCULATE GENOMIC WINDOW COORDINATES
# ============================================================
#
# PLUS STRAND
#
#   genomic:
#
#     translation_start - upstream
#       ...
#     translation_start + downstream
#
#
# MINUS STRAND
#
#   genomic interval is reversed:
#
#     translation_start - downstream
#       ...
#     translation_start + upstream
#
# followed by reverse complementation.

window_table <- window_table |>
  dplyr::mutate(
    
    window_genomic_start =
      dplyr::case_when(
        
        strand == "+" ~
          
          translation_start -
          window_upstream_nt,
        
        
        strand == "-" ~
          
          translation_start -
          window_downstream_nt,
        
        
        TRUE ~
          
          NA_integer_
      ),
    
    
    window_genomic_end =
      dplyr::case_when(
        
        strand == "+" ~
          
          translation_start +
          window_downstream_nt,
        
        
        strand == "-" ~
          
          translation_start +
          window_upstream_nt,
        
        
        TRUE ~
          
          NA_integer_
      ),
    
    
    wraps_origin =
      window_genomic_start < 1 |
      window_genomic_end >
      genome_length
  )



