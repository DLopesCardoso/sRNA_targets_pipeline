# ============================================================
# 08_prepare_motif_windows.R
#
# Aim
# ---
# Generate strand-aware genomic sequence windows around the
# translation start of:
#
#   1. predicted sRNA target genes;
#   2. non-target background genes.
#
# These sequences are intended for motif analysis in Script 09
# and can also be used as input for MEME-suite tools.
#
#
# WINDOW DEFINITION
# -----------------
#
# Default:
#
#     -200 nt upstream of CDS start
#       through
#     +100 nt downstream of CDS start
#
# Coordinates are defined relative to the translation start:
#
#     -200 ... -1 | 0 | +1 ... +100
#
# giving a 301-nt sequence.
#
# All extracted sequences are oriented in the direction of
# transcription:
#
#     + strand = genomic sequence
#     - strand = reverse complement
#
#
# CANDIDATE SET
# -------------
#
# The candidate FASTA contains the harmonised annotated target
# set generated by Script 01.
#
#
# BACKGROUND SET
# --------------
#
# The background contains all reference genes with valid genomic
# coordinates that are NOT members of the candidate set.
#
# The same sequence window and strand-aware extraction are
# applied to candidates and background genes.
#
#
# INPUTS
# ------
#
# results/tables/
#   target_candidates_annotated.csv
#
# data/reference/
#   reference_gene_coordinates.csv
#
# AND either:
#
# data/reference/
#   reference_genome.fasta
#
# OR:
#
# data/reference/
#   reference_genome.gbff
#
#
# OUTPUTS
# -------
#
# results/motif/
#   candidate_windows_minus200_plus100.fasta
#   background_windows_minus200_plus100.fasta
#
# results/tables/
#   motif_window_metadata.csv
#   motif_window_qc.csv
#
# ============================================================



