# ============================================================
# DEFINE OPERON STATUS
# ============================================================

target_operons <- target_operons |>
  dplyr::mutate(
    
    operon_status =
      dplyr::case_when(
        
        mapping_method == "unmapped" ~
          "Unmapped",
        
        is.na(operon_id) ~
          "No operon assignment",
        
        operon_size == 1L ~
          "Single-gene operon",
        
        operon_role == "first" ~
          "First gene in polycistronic operon",
        
        operon_role == "internal" ~
          "Internal gene in polycistronic operon",
        
        operon_role == "last" ~
          "Last gene in polycistronic operon",
        
        TRUE ~
          "Review"
      ),
    
    
    internal_polycistronic =
      dplyr::case_when(
        
        operon_size > 1L &
          operon_role %in%
          c(
            "internal",
            "last"
          ) ~
          
          TRUE,
        
        operon_size >= 1L ~
          
          FALSE,
        
        TRUE ~
          
          NA
      ),
    
    
    first_gene_in_operon =
      dplyr::case_when(
        
        operon_role %in%
          c(
            "first",
            "single"
          ) ~
          
          TRUE,
        
        operon_role %in%
          c(
            "internal",
            "last"
          ) ~
          
          FALSE,
        
        TRUE ~
          
          NA
      ),
    
    
    mapping_review_flag =
      dplyr::case_when(
        
        mapping_method ==
          "coordinate_overlap" ~
          
          "review_coordinate_overlap",
        
        mapping_method ==
          "unmapped" ~
          
          "unmapped_to_OperonMapper_ORF",
        
        TRUE ~
          
          ""
      )
  )



