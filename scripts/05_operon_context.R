# ============================================================
# 05_operon_context.R
#
# Aim
# ---
# Assign Operon-mapper operon context to the harmonised GcvB
# candidate target genes.
#
#
# WORKFLOW
# --------
#
# 1. Import the harmonised candidate target list.
# 2. Add reference genomic coordinates and strand.
# 3. Import Operon-mapper ORF coordinates.
# 4. Parse Operon-mapper predicted operons.
# 5. Order operon members in transcriptional direction.
# 6. Map each candidate gene to an Operon-mapper ORF using:
#       a. exact coordinates + strand;
#       b. >=80% reciprocal coordinate overlap as fallback.
# 7. Assign:
#       - operon ID
#       - operon size
#       - position within operon
#       - first/internal/last role
#       - operon genomic boundaries
#       - first and last ORF
#       - ordered operon member list
#       - previous and next ORF
# 8. Export QC summaries and the downstream operon-context file.
#
#
# IMPORTANT
# ---------
#
# This script describes operon context only.
#
# It does NOT decide the final transcript start or 5' UTR.
# Those decisions should be made later by integrating the
# Operon-mapper context with the TSS evidence from Script 04.
#
#
# OPERON-MAPPER INPUT
# -------------------
#
# Operon predictions should be generated by submitting the
# reference genome to Operon-mapper; the resulting
# "list_of_operons" and "ORFs_coordinates" files are required
# as inputs for this script.
#
#
# INPUTS
# ------
#
# results/tables/target_candidates_annotated.csv
#
# data/reference/reference_gene_coordinates.csv
#
# data/raw/operon_mapper/
#   list_of_operons_*
#   ORFs_coordinates_*
#
#
# OUTPUTS
# -------
#
# results/tables/operon_context.csv
# results/tables/operon_mapper_all_operons.csv
# results/tables/operon_mapper_all_orfs.csv
# results/tables/operon_context_summary.csv
# results/tables/operon_context_qc.csv
#
# ============================================================



