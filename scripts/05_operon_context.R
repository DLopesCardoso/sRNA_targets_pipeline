# ============================================================
# HELPER: CHECK REQUIRED COLUMNS
# ============================================================

check_columns <- function(
    df,
    required,
    label
) {
  
  missing_columns <- setdiff(
    required,
    names(df)
  )
  
  
  if (length(missing_columns) > 0) {
    
    stop(
      label,
      " is missing required column(s):\n",
      paste(
        missing_columns,
        collapse = ", "
      ),
      "\n\nAvailable columns:\n",
      paste(
        names(df),
        collapse = ", "
      )
    )
  }
}



# ============================================================
# HELPER: LOCATE ONE OPERON-MAPPER FILE
# ============================================================

find_one_file <- function(
    directory,
    pattern,
    label
) {
  
  hits <- list.files(
    directory,
    pattern = pattern,
    full.names = TRUE,
    ignore.case = TRUE
  )
  
  
  if (length(hits) == 0) {
    
    stop(
      "Could not find ",
      label,
      " in:\n",
      directory
    )
  }
  
  
  hits <- hits[
    order(
      nchar(basename(hits)),
      basename(hits)
    )
  ]
  
  
  if (length(hits) > 1) {
    
    warning(
      "Multiple files matched ",
      label,
      ". Using:\n",
      basename(hits[1])
    )
  }
  
  
  message(
    label,
    ": ",
    basename(hits[1])
  )
  
  
  return(hits[1])
}



