# ============================================================
# PARSE list_of_operons
# ============================================================
#
# Format:
#
# Operon IdGene Type COGgene PosLeft postRight Strand Function
#
# followed by:
#
# 1
#     dnaA    CDS ...
#     dnaN    CDS ...
#
# 2
#     sodC    CDS ...
#
# etc.

parse_operons <- function(
    path
) {
  
  lines <- readLines(
    path,
    warn = FALSE,
    encoding = "UTF-8"
  )
  
  
  if (length(lines) == 0) {
    
    stop(
      "Operon file is empty:\n",
      path
    )
  }
  
  
  # Remove header.
  
  lines <- lines[-1]
  
  
  # Remove blank lines.
  
  lines <- lines[
    nzchar(
      trimws(lines)
    )
  ]
  
  
  current_operon <- NA_integer_
  
  out <- list()
  
  k <- 0L
  
  
  for (line in lines) {
    
    z <- trimws(line)
    
    
    # A line containing only an integer defines a new operon.
    
    if (
      grepl(
        "^[0-9]+$",
        z
      )
    ) {
      
      current_operon <-
        as.integer(z)
      
      next
    }
    
    
    fields <- strsplit(
      line,
      "\t",
      fixed = TRUE
    )[[1]]
    
    
    # Remove empty fields introduced by leading tab.
    
    fields <- fields[
      nzchar(fields)
    ]
    
    
    if (length(fields) >= 6) {
      
      k <- k + 1L
      
      
      out[[k]] <- tibble::tibble(
        
        operon_id =
          current_operon,
        
        operonmapper_id =
          fields[1],
        
        feature_type =
          fields[2],
        
        COG =
          fields[3],
        
        pos_left =
          suppressWarnings(
            as.integer(fields[4])
          ),
        
        pos_right =
          suppressWarnings(
            as.integer(fields[5])
          ),
        
        strand =
          fields[6],
        
        function_text =
          if (length(fields) >= 7) {
            
            paste(
              fields[7:length(fields)],
              collapse = "\t"
            )
            
          } else {
            
            NA_character_
          }
      )
    }
  }
  
  
  result <- dplyr::bind_rows(out)
  
  
  if (nrow(result) == 0) {
    
    stop(
      "No operon members could be parsed from:\n",
      path
    )
  }
  
  
  return(result)
}



operon_members <- parse_operons(
  operons_file
)



# ============================================================
# STANDARDISE OPERON COORDINATES
# ============================================================

operon_members <- operon_members |>
  dplyr::mutate(
    
    operon_member_left =
      pmin(
        pos_left,
        pos_right
      ),
    
    operon_member_right =
      pmax(
        pos_left,
        pos_right
      )
  )



# ============================================================
# ORDER MEMBERS IN TRANSCRIPTIONAL DIRECTION
# ============================================================
#
# + strand:
#
#   lower coordinate -> higher coordinate
#
# - strand:
#
#   higher coordinate -> lower coordinate

operon_members <- operon_members |>
  dplyr::mutate(
    
    transcription_order_coordinate =
      dplyr::case_when(
        
        strand == "+" ~
          operon_member_left,
        
        strand == "-" ~
          -operon_member_right,
        
        TRUE ~
          NA_real_
      )
  ) |>
  dplyr::group_by(
    operon_id
  ) |>
  dplyr::arrange(
    transcription_order_coordinate,
    .by_group = TRUE
  ) |>
  dplyr::mutate(
    
    operon_size =
      dplyr::n(),
    
    operon_position =
      dplyr::row_number(),
    
    operon_role =
      dplyr::case_when(
        
        operon_size == 1L ~
          "single",
        
        operon_position == 1L ~
          "first",
        
        operon_position == operon_size ~
          "last",
        
        TRUE ~
          "internal"
      ),
    
    previous_orf =
      dplyr::lag(
        operonmapper_id
      ),
    
    next_orf =
      dplyr::lead(
        operonmapper_id
      ),
    
    operon_first_orf =
      dplyr::first(
        operonmapper_id
      ),
    
    operon_last_orf =
      dplyr::last(
        operonmapper_id
      ),
    
    operon_left =
      min(
        operon_member_left,
        na.rm = TRUE
      ),
    
    operon_right =
      max(
        operon_member_right,
        na.rm = TRUE
      ),
    
    operon_members_ordered =
      paste(
        operonmapper_id,
        collapse = ";"
      )
    
  ) |>
  dplyr::ungroup() |>
  dplyr::select(
    -transcription_order_coordinate
  )



# ============================================================
# JOIN OPERON INFORMATION TO ORF TABLE
# ============================================================

orfs_with_operon <- orfs |>
  dplyr::left_join(
    
    operon_members |>
      dplyr::select(
        
        operonmapper_id,
        
        operon_id,
        operon_size,
        operon_position,
        operon_role,
        
        previous_orf,
        next_orf,
        
        operon_first_orf,
        operon_last_orf,
        
        operon_left,
        operon_right,
        
        operon_members_ordered
      ),
    
    by = "operonmapper_id"
  )



# ============================================================
# EXACT TARGET -> ORF MAPPING
# ============================================================
#
# Match on:
#
#   strand
#   target left coordinate
#   target right coordinate
#
# The many-to-many relationship is intentional at this stage
# because all same-strand ORFs are initially compared before
# exact coordinate filtering.

exact_candidates <- dplyr::inner_join(
  targets,
  orfs_with_operon,
  by = "strand",
  relationship = "many-to-many"
) |>
  dplyr::filter(
    target_left == orf_left,
    target_right == orf_right
  )



# ============================================================
# RESOLVE EXACT-MATCH DUPLICATES
# ============================================================

exact <- exact_candidates |>
  dplyr::group_by(
    reference_locus
  ) |>
  dplyr::arrange(
    operonmapper_id,
    .by_group = TRUE
  ) |>
  dplyr::mutate(
    match_rank =
      dplyr::row_number()
  ) |>
  dplyr::filter(
    match_rank == 1L
  ) |>
  dplyr::ungroup() |>
  dplyr::mutate(
    
    mapping_method =
      "exact_coordinates",
    
    mapping_overlap =
      1
  )



# ============================================================
# TARGETS WITHOUT EXACT MATCH
# ============================================================

unmatched <- targets |>
  dplyr::anti_join(
    exact |>
      dplyr::select(
        reference_locus
      ),
    by = "reference_locus"
  )



# ============================================================
# FALLBACK COORDINATE-OVERLAP MAPPING
# ============================================================
#
# Require at least 80% overlap relative to BOTH:
#
#   target length
#   Operon-mapper ORF length
#
# The minimum of these two fractions is used.

fallback_candidates <- dplyr::inner_join(
  unmatched,
  orfs_with_operon,
  by = "strand",
  relationship = "many-to-many"
) |>
  dplyr::mutate(
    
    overlap_bp =
      pmax(
        0L,
        pmin(
          target_right,
          orf_right
        ) -
          pmax(
            target_left,
            orf_left
          ) +
          1L
      ),
    
    overlap_target =
      overlap_bp /
      target_length,
    
    overlap_orf =
      overlap_bp /
      orf_length,
    
    minimum_reciprocal_overlap =
      pmin(
        overlap_target,
        overlap_orf
      ),
    
    coordinate_difference =
      abs(
        target_left -
          orf_left
      ) +
      abs(
        target_right -
          orf_right
      )
  ) |>
  dplyr::filter(
    minimum_reciprocal_overlap >=
      minimum_overlap
  )



# ============================================================
# SELECT BEST FALLBACK MATCH
# ============================================================

fallback <- fallback_candidates |>
  dplyr::group_by(
    reference_locus
  ) |>
  dplyr::arrange(
    
    dplyr::desc(
      minimum_reciprocal_overlap
    ),
    
    coordinate_difference,
    
    operonmapper_id,
    
    .by_group = TRUE
  ) |>
  dplyr::mutate(
    match_rank =
      dplyr::row_number()
  ) |>
  dplyr::filter(
    match_rank == 1L
  ) |>
  dplyr::ungroup() |>
  dplyr::mutate(
    
    mapping_method =
      "coordinate_overlap",
    
    mapping_overlap =
      minimum_reciprocal_overlap
  )



# ============================================================
# COMBINE MAPPED TARGETS
# ============================================================

mapped <- dplyr::bind_rows(
